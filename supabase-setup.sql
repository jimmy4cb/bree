create table if not exists public.user_roles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'user' check (role in ('user', 'admin'))
);

alter table public.user_roles enable row level security;
grant usage on schema public to authenticated;
revoke all on public.user_roles from public, anon, authenticated;
grant select on public.user_roles to authenticated;

drop policy if exists "Users can read their own role" on public.user_roles;
create policy "Users can read their own role"
  on public.user_roles
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

create or replace function public.assign_default_user_role()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.user_roles (user_id, role)
  values (new.id, 'user')
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_assign_role on auth.users;
create trigger on_auth_user_created_assign_role
  after insert on auth.users
  for each row execute procedure public.assign_default_user_role();

insert into public.user_roles (user_id, role)
select id, 'user'
from auth.users
on conflict (user_id) do nothing;

update public.user_roles as roles
set role = 'admin'
from auth.users as users
where users.id = roles.user_id
  and users.email = 'clii@jijengeyouth.org';

create table if not exists public.user_activity (
  activity_id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete cascade,
  visitor_id uuid,
  event text not null check (event in (
    'consent_accepted',
    'consent_declined',
    'retry_clicked',
    'not_now_clicked',
    'calendar_add_clicked',
    'calendar_reminder_created',
    'activity_refresh_clicked',
    'signed_in',
    'account_created',
    'signed_out'
  )),
  created_at timestamptz not null default now()
);

alter table public.user_activity alter column user_id drop not null;
alter table public.user_activity add column if not exists visitor_id uuid;
alter table public.user_activity enable row level security;
revoke all on public.user_activity from public, anon, authenticated;
grant insert, select on public.user_activity to authenticated;
grant insert on public.user_activity to anon;

drop policy if exists "Users can record their own activity" on public.user_activity;
create policy "Users can record their own activity"
  on public.user_activity
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Visitors can record anonymous activity" on public.user_activity;
create policy "Visitors can record anonymous activity"
  on public.user_activity
  for insert
  to anon
  with check (user_id is null and visitor_id is not null);

drop policy if exists "Admins can read activity" on public.user_activity;
create policy "Admins can read activity"
  on public.user_activity
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.user_roles as roles
      where roles.user_id = (select auth.uid())
        and roles.role = 'admin'
    )
  );

create or replace function public.record_new_user_activity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.user_activity (user_id, event)
  values (new.id, 'account_created');
  return new;
end;
$$;

revoke all on function public.record_new_user_activity() from public, anon, authenticated;

drop trigger if exists on_auth_user_created_record_activity on auth.users;
create trigger on_auth_user_created_record_activity
  after insert on auth.users
  for each row execute procedure public.record_new_user_activity();